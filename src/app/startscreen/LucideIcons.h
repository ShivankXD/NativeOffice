// Renders a Lucide SVG (stroke="currentColor") into a crisp hi-dpi pixmap.
inline QPixmap pixmap(const char* svg, const QString& colorHex, int size, qreal dpr = 1.0) {
    QByteArray data(svg);
    data.replace("currentColor", colorHex.toUtf8());
    QSvgRenderer renderer(data);
    QPixmap pm(int(size * dpr), int(size * dpr));
    pm.fill(Qt::transparent);
    QPainter p(&pm);
    p.setRenderHint(QPainter::Antialiasing);
    renderer.render(&p);
    p.end();
    pm.setDevicePixelRatio(dpr);
    return pm;
}

inline QIcon icon(const char* svg, const QString& colorHex, int size, qreal dpr = 1.0) {
    return QIcon(pixmap(svg, colorHex, size, dpr));
}

// A transparent QLabel showing the icon — clicks pass through to the parent.
inline QLabel* label(const char* svg, const QString& colorHex, int size, QWidget* parent) {
    auto* l = new QLabel(parent);
    const qreal dpr = parent ? parent->devicePixelRatio() : 1.0;
    l->setPixmap(pixmap(svg, colorHex, size, dpr));
    l->setFixedSize(size, size);
    l->setStyleSheet("background:transparent;");
    l->setAttribute(Qt::WA_TransparentForMouseEvents);
    return l;
}

